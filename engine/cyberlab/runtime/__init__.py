from typing import Protocol

from cyberlab.session import Session


class RuntimeFailure(Exception):
    """A sanitized runtime failure suitable for returning to clients."""

class TerminalStream(Protocol):
    def read(self, limit: int) -> tuple[bytes, bool]: ...

    def write(self, data: bytes) -> int: ...

    def resize(self, rows: int, columns: int) -> None: ...

    def exited(self) -> bool: ...

    def close(self) -> None: ...


class Runtime(Protocol):
    name: str

    def start(self, session: Session, workspaces: dict | None = None) -> None: ...

    def remove(self, session_id: str) -> None: ...

    def running(self, session: Session) -> bool: ...

    def cleanup(self) -> None: ...

    def open_terminal(self, session: Session, node_id: str) -> TerminalStream: ...

    def import_file(self, session: Session, record, data: bytes) -> None: ...

    def workspace(self, session: Session, node): ...

    def import_workspace(self, session: Session, node, name: str, entries) -> None: ...
