const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../ui/studio/models/AssessmentModel.js'), 'utf8').replace(/^\.pragma library\s*/, ''), context);
const update = context.updateResult;
const result = {operator: 'field_equals', expected: 'old', field_type: 'token', field_id: 1, line_type: 'line', line_id: 1};
update(result, 'operator', 'collect');
assert.equal(result.expected, undefined);
assert.equal(result.field_type, 'token');
update(result, 'field_type', 'contains');
update(result, 'field_id', 'FAILED LOGIN');
update(result, 'timestamp_type', 'log_ts');
assert.equal(result.field_id, 'FAILED LOGIN');
assert.equal(result.line_type, undefined);
update(result, 'field_type', 'size');
for (const field of ['field_id', 'line_type', 'line_id', 'timestamp_type']) assert.equal(result[field], undefined);
update(result, 'field_type', 'search');
assert.equal(result.line_type, 'none');
update(result, 'line_type', 'line');
assert.equal(result.line_id, 1);
update(result, 'timestamp_type', 'log_ts');
assert.equal(result.line_type, 'none');
assert.equal(result.line_id, undefined);
update(result, 'field_type', 'group');
assert.equal(result.timestamp_type, undefined);
assert.equal(result.line_type, 'regex');
update(result, 'line_type', 'none');
assert.equal(result.field_type, 'token');
assert.equal(result.line_id, undefined);
update(result, 'field_type', 'param');
update(result, 'field_id', '0');
assert.equal(result.field_id, 0);
assert.throws(() => update(result, 'field_id', '-1'));
update(result, 'operator', 'exists');
for (const field of ['field_id', 'field_type', 'line_type', 'line_id', 'timestamp_type', 'expected']) assert.equal(result[field], undefined);
console.log('Result model transitions passed');
